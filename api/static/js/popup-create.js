/**
 * @file popup creation cleanup actions
 * @description Removes secondary form action buttons and links from popup.
 *
 * This script removes actions such as:
 * - "Add another";
 * - "Continue editing";
 * - "Cancel";
 * - secondary default or danger links in form actions.
 *
 * It also enables Bootstrap tooltips when jQuery is available.
 *
 * @author L. Terriel
 * @copyright 2025 MPN/ENC
 */

(function () {
    /**
     * Remove secondary Flask-Admin action buttons and links from the popup.
     *
     * The function targets both input and button submit controls, as well as
     * secondary action links commonly generated by Flask-Admin templates.
     *
     * Elements are removed when:
     * - their selector explicitly targets `_add_another` or `_continue_editing`;
     * - their visible text or value contains labels such as "annuler",
     *   "continue", or "ajouter un autre".
     *
     * @returns {void}
     */
    function removeSecondaryButtons() {
        /**
         * CSS selectors matching secondary Flask-Admin actions.
         *
         * @type {string[]}
         */
        const selectors = [
            'input[name="_add_another"]',
            'input[name="_continue_editing"]',
            'button[name="_add_another"]',
            'button[name="_continue_editing"]',
            '.form-actions a',
            '.btn-default[href]',
            '.btn-danger[href]',
        ];

        selectors.forEach(selector => {
            document.querySelectorAll(selector).forEach(el => {
                const text = (el.textContent || '').trim().toLowerCase();
                const value = (el.value || '').trim().toLowerCase();

                if (
                    selector.includes('_add_another') ||
                    selector.includes('_continue_editing') ||
                    text.includes('annuler') ||
                    value.includes('annuler') ||
                    text.includes('continue') ||
                    value.includes('continue') ||
                    text.includes('ajouter un autre') ||
                    value.includes('ajouter un autre')
                ) {
                    el.remove();
                }
            });
        });
    }

    /**
     * Run cleanup once the DOM is ready and enable Bootstrap tooltips if available.
     *
     * @returns {void}
     */
    document.addEventListener('DOMContentLoaded', function () {
        removeSecondaryButtons();

        if (window.jQuery) {
            $('[data-toggle="tooltip"]').tooltip();
        }
    });

    /**
     * Run cleanup again after the full page load.
     *
     * This catches buttons or links injected late by Flask-Admin extensions,
     * templates, or browser autofill-related rendering.
     */
    window.addEventListener('load', removeSecondaryButtons);
})();